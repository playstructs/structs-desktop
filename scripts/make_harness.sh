#!/usr/bin/env bash
# Build the static board harness: frontend/_harness.html + frontend/_fixtures.js.
#
# Why this exists: a signed rebuild is ~20 minutes, and the board pages are
# plain JS against a tiny __TAURI__ surface — so we splice a fixture-backed
# stub in FRONT of board-shim.js (the shim bails out when __TAURI__ already
# exists) and drive the real board.html in any browser or in jsdom
# (scripts/harness-tests/). No Tauri, no MCP server, no login.
#
#   bash scripts/make_harness.sh
#   (cd frontend && python3 -m http.server 8899)
#   open http://localhost:8899/_harness.html?view=gamestats
#   variants:  &fixture=unauth   &fixture=coldboot
#
# Test hooks exposed on window:
#   __HARNESS_CALLS__      — every core.invoke {cmd, args}, in order
#   __HARNESS_LISTENERS__  — event name → [callbacks]; dispatch synthetic
#                            events with __HARNESS_EMIT__(name, payload)
#
# BOTH generated files are gitignored and MUST NOT exist when the app is
# built — they would ship in frontendDist.
set -euo pipefail
cd "$(dirname "$0")/.."

SRC=frontend/board.html
OUT=frontend/_harness.html
FIX=frontend/_fixtures.js

[ -f "$SRC" ] || { echo "missing $SRC (run from the repo)"; exit 1; }

